// Generates infra/supabase/seed.sql from packages/requirements/*.yaml.
// requirement_packs is real seeded data (case_files.requirement_pack_id is a
// foreign key into it) — the YAML packs are the source of truth, this script
// is the only thing that should produce or touch seed.sql.
import { readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import { load } from 'js-yaml'

const __dirname = dirname(fileURLToPath(import.meta.url))
const repoRoot = join(__dirname, '../../..')
const requirementsDir = join(repoRoot, 'packages/requirements')
const seedPath = join(repoRoot, 'infra/supabase/seed.sql')

function sqlString(value) {
  return `'${value.replace(/'/g, "''")}'`
}

const files = readdirSync(requirementsDir)
  .filter((file) => file.endsWith('.yaml'))
  .sort()

const statements = files.map((file) => {
  const pack = load(readFileSync(join(requirementsDir, file), 'utf8'))
  const requirementsJson = JSON.stringify(pack.requirements)

  return `insert into requirement_packs (jurisdiction_code, version, requirements)
values (${sqlString(pack.jurisdiction_code)}, ${pack.version}, ${sqlString(requirementsJson)}::jsonb)
on conflict (jurisdiction_code, version) do update set requirements = excluded.requirements;`
})

const contents = `-- Generated by apps/web/scripts/build-requirements-seed.mjs from
-- packages/requirements/*.yaml. Do not hand-edit: change the source YAML
-- and rerun \`npm run seed:requirements\` in apps/web.

${statements.join('\n\n')}
`

writeFileSync(seedPath, contents)
console.log(`Wrote ${statements.length} requirement pack(s) to ${seedPath}`)
